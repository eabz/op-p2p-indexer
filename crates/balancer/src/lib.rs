//! The balancer: the directory of a deployment's servers for one chain (`docs/serving.md`
//! section 6). No block data passes through it: it tells clients which servers to read from,
//! and they read from the servers directly.
//!
//! ```text
//! servers ─Register (heartbeats)─▶ table ─┐
//! R2 manifest (every 30 s) ───────────────┼─▶ Flight GetFlightInfo, ListFlights: per-chunk jobs
//!                                         └─▶ Locate: servers for a subscription
//! ```
//!
//! - `table`: the servers registered now, with their heads and load, from their heartbeats.
//!   A server is in it while its `Register` call is open and its heartbeats arrive.
//! - `service`: the gRPC service, `Register` (server key) and `Locate` (user key).
//! - `flight`: Arrow Flight's `GetFlightInfo` and `ListFlights` (user key): a range cut into
//!   one endpoint per sealed chunk, each naming servers by load, and the part above the last
//!   sealed chunk naming the servers whose head covers it with no hole below it.
//! - [`register`]: the server's side, the client that keeps a server registered.
//!
//! [`Balancer`] is the component.

