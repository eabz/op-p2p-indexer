//! The chain, streamed to consumers over gRPC: history from the block archive, then the live
//! chain from the unsafe store, each block with its status, and reorgs and status changes as
//! their own messages. See `docs/stream.md`.
//!
//! ```text
//! UnsafeStore events ─┐
//! ArchiveStore heads ─┴─▶ follower ─▶ window of events ─┐
//!                                                       ├─▶ subscriptions ─▶ gRPC
//! ArchiveStore, UnsafeStore (history, per subscription) ┘
//! ```
//!
//! Next to it, on the same listener, an Arrow Flight service serves ranges of history as
//! columnar record batches (`flight`).
//!
//! [`StreamServer`] is the component; it only reads the stores.

